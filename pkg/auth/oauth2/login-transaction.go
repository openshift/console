const (
	loginTransactionPrefix = "oidc-login-"
	loginTransactionAge    = 300
	loginTransactionLimit  = 3800
	pkceNone               = "none"
	pkceS256               = "s256"
)

type oidcProviderSnapshot struct {
	provider *oidc.Provider
	mode     string
}

// discoverOIDCProvider validates discovery and selects PKCE as one cache snapshot.
// Errors deliberately omit provider-controlled response bodies and issuer values.
func discoverOIDCProvider(ctx context.Context, config *oidcConfig) (*oidcProviderSnapshot, error) {
	provider, err := oidc.NewProvider(oidc.ClientContext(ctx, config.getClient()), config.issuerURL)
	if err != nil {
		return nil, fmt.Errorf("OIDC discovery failed")
	}
	var metadata struct {
		Methods json.RawMessage `json:"code_challenge_methods_supported"`
	}
	if err := provider.Claims(&metadata); err != nil {
		return nil, fmt.Errorf("invalid OIDC discovery metadata")
	}
	mode, err := discoveryPKCEMode(metadata.Methods)
	if err != nil {
		return nil, err
	}
	return &oidcProviderSnapshot{provider: provider, mode: mode}, nil
}

// discoveryPKCEMode enables PKCE only for an explicit S256 advertisement and
// rejects malformed capabilities rather than treating them as unsupported.
func discoveryPKCEMode(raw json.RawMessage) (string, error) {
	if len(raw) == 0 {
		return pkceNone, nil
	}
	var methods []json.RawMessage
	if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) || json.Unmarshal(raw, &methods) != nil {
		return "", fmt.Errorf("invalid OIDC code challenge methods")
	}
	mode := pkceNone
	for _, method := range methods {
		var name string
		if bytes.Equal(bytes.TrimSpace(method), []byte("null")) || json.Unmarshal(method, &name) != nil {
			return "", fmt.Errorf("invalid OIDC code challenge method")
		}
		if name == "S256" {
			mode = pkceS256
		}
	}
	return mode, nil
}

type loginTransaction struct {
	Version     int    `json:"version"`
	State       string `json:"state"`
	Mode        string `json:"mode"`
	Verifier    string `json:"verifier,omitempty"`
	IssuedAt    int64  `json:"issued_at"`
	ExpiresAt   int64  `json:"expires_at"`
	Issuer      string `json:"issuer"`
	ClientID    string `json:"client_id"`
	RedirectURI string `json:"redirect_uri"`
}

type loginTransactions struct {
	codecs []securecookie.Codec
	now    func() time.Time
}

// newLoginTransactions writes with current keys and accepts current or previous
// keys when reading authenticated, encrypted, short-lived login transactions.
func newLoginTransactions(config *oidcConfig) (*loginTransactions, error) {
	keyPairs := [][]byte{config.cookieAuthenticationKey, config.cookieEncryptionKey}
	if len(config.previousCookieAuthenticationKey) > 0 && len(config.previousCookieEncryptionKey) > 0 {
		keyPairs = append(keyPairs, config.previousCookieAuthenticationKey, config.previousCookieEncryptionKey)
	}
	codecs := make([]securecookie.Codec, 0, len(keyPairs)/2)
	for keyIndex := 0; keyIndex < len(keyPairs); keyIndex += 2 {
		if len(keyPairs[keyIndex]) == 0 || len(keyPairs[keyIndex+1]) == 0 {
			return nil, fmt.Errorf("OIDC login transaction keys are required")
		}
		codec := securecookie.New(keyPairs[keyIndex], keyPairs[keyIndex+1]).
			SetSerializer(securecookie.JSONEncoder{}).MaxAge(loginTransactionAge).MaxLength(loginTransactionLimit)
		if _, err := codec.Encode(loginTransactionPrefix, struct{}{}); err != nil {
			return nil, fmt.Errorf("invalid OIDC login transaction keys")
		}
		codecs = append(codecs, codec)
	}
	return &loginTransactions{codecs: codecs, now: time.Now}, nil
}

// transactionCookie scopes a host-only cookie to the callback directory, using
// Lax SameSite so a cross-site authorization redirect can return the transaction.
func transactionCookie(name, redirectURI string, secure bool) (*http.Cookie, error) {
	redirect, err := url.Parse(redirectURI)
	if err != nil {
		return nil, fmt.Errorf("invalid OIDC callback URL")
	}
	cookiePath := path.Dir(redirect.EscapedPath())
	if cookiePath != "/" {
		cookiePath += "/"
	}
	return &http.Cookie{Name: name, Path: cookiePath, HttpOnly: true, Secure: secure, SameSite: http.SameSiteLaxMode}, nil
}

// validLoginState accepts only the fixed-length lowercase hexadecimal state
// generated by this authenticator, before cookie lookup or state comparison.
func validLoginState(state string) bool {
	decoded, err := hex.DecodeString(state)
	return err == nil && len(state) == stateLength && hex.EncodeToString(decoded) == state
}

// read validates the protected transaction, its server-side lifetime and request
// context without choosing a new PKCE mode from refreshed discovery metadata.
func (store *loginTransactions) read(r *http.Request, config *oauth2.Config, issuer string) (*loginTransaction, error) {
	redirect, err := url.Parse(config.RedirectURL)
	if err != nil || redirect.Host != r.Host || redirect.Path != r.URL.Path {
		return nil, fmt.Errorf("invalid OIDC callback context")
	}
	states := r.URL.Query()["state"]
	if len(states) != 1 || !validLoginState(states[0]) {
		return nil, fmt.Errorf("invalid OIDC login state")
	}
	name := loginTransactionPrefix + states[0]
	var candidate *http.Cookie
	for _, cookie := range r.Cookies() {
		if cookie.Name == name {
			if candidate != nil {
				return nil, fmt.Errorf("duplicate OIDC login transaction")
			}
			candidate = cookie
		}
	}
	if candidate == nil || len(candidate.Value) > loginTransactionLimit {
		return nil, fmt.Errorf("missing OIDC login transaction")
	}
	var transaction loginTransaction
	if err := securecookie.DecodeMulti(name, candidate.Value, &transaction, store.codecs...); err != nil {
		return nil, fmt.Errorf("invalid OIDC login transaction")
	}
	now := store.now().Unix()
	if transaction.Version != 1 || !validLoginState(transaction.State) ||
		subtle.ConstantTimeCompare([]byte(transaction.State), []byte(states[0])) != 1 || transaction.Issuer != issuer ||
		transaction.ClientID != config.ClientID || transaction.RedirectURI != config.RedirectURL ||
		transaction.IssuedAt > now || transaction.ExpiresAt <= now ||
		transaction.ExpiresAt-transaction.IssuedAt != loginTransactionAge {
		return nil, fmt.Errorf("expired or mismatched OIDC login transaction")
	}
	switch transaction.Mode {
	case pkceNone:
		if transaction.Verifier != "" {
			return nil, fmt.Errorf("unexpected OIDC verifier")
		}
	case pkceS256:
		if !validVerifier(transaction.Verifier) {
			return nil, fmt.Errorf("invalid OIDC verifier")
		}
	default:
		return nil, fmt.Errorf("invalid OIDC login mode")
	}
	return &transaction, nil
}

// validVerifier enforces the RFC 7636 length and unreserved character set.
func validVerifier(verifier string) bool {
	if len(verifier) < 43 || len(verifier) > 128 {
		return false
	}
	for _, character := range verifier {
		if !(character >= 'a' && character <= 'z' || character >= 'A' && character <= 'Z' ||
			character >= '0' && character <= '9' || character == '-' || character == '.' || character == '_' || character == '~') {
			return false
		}
	}
	return true
}

func (a *OAuth2Authenticator) oidcLogin(w http.ResponseWriter, r *http.Request) {
	method := a.loginMethod.(*oidcAuth)
	snapshot := method.providerCache.GetItem()
	config := a.configForHost(a.oauth2ConfigConstructor(snapshot.provider.Endpoint()), r.Host)
	var randomState [16]byte
	if _, err := rand.Read(randomState[:]); err != nil {
		a.redirectAuthError(w, errorInternal)
		return
	}
	issued := a.oidcTransactions.now()
	transaction := loginTransaction{
		Version: 1, State: hex.EncodeToString(randomState[:]), Mode: snapshot.mode,
		IssuedAt: issued.Unix(), ExpiresAt: issued.Add(loginTransactionAge * time.Second).Unix(),
		Issuer: method.issuerURL, ClientID: config.ClientID, RedirectURI: config.RedirectURL,
	}
	var options []oauth2.AuthCodeOption
	if transaction.Mode == pkceS256 {
		transaction.Verifier = oauth2.GenerateVerifier()
		options = append(options, oauth2.S256ChallengeOption(transaction.Verifier))
	}
	cookie, err := transactionCookie(loginTransactionPrefix+transaction.State, config.RedirectURL, a.secureCookies)
	if err != nil {
		a.redirectAuthError(w, errorInternal)
		return
	}
	encoded, err := a.oidcTransactions.codecs[0].Encode(cookie.Name, transaction)
	if err != nil {
		a.redirectAuthError(w, errorInternal)
		return
	}
	cookie.Value, cookie.MaxAge, cookie.Expires = encoded, loginTransactionAge, issued.Add(loginTransactionAge*time.Second)
	http.SetCookie(w, cookie)
	http.Redirect(w, r, config.AuthCodeURL(transaction.State, options...), http.StatusSeeOther)
}

func (a *OAuth2Authenticator) oidcCallback(w http.ResponseWriter, r *http.Request, complete func(sessions.LoginJSON, string, http.ResponseWriter)) {
	method := a.loginMethod.(*oidcAuth)
	config := a.oauth2ConfigForHost(r.Host)
	if r.Method != http.MethodGet {
		a.redirectAuthError(w, errorInvalidState)
		return
	}
	query := r.URL.Query()
	state := query.Get("state")
	if validLoginState(state) {
		cookie, err := transactionCookie(loginTransactionPrefix+state, config.RedirectURL, a.secureCookies)
		if err != nil {
			a.redirectAuthError(w, errorInvalidState)
			return
		}
		cookie.MaxAge = -1
		http.SetCookie(w, cookie)
	}
	transaction, err := a.oidcTransactions.read(r, config, method.issuerURL)
	if err != nil {
		a.redirectAuthError(w, errorInvalidState)
		return
	}
	if len(query["error"]) > 0 {
		a.redirectAuthError(w, errorOAuth)
		return
	}
	if len(query["code"]) != 1 || query.Get("code") == "" {
		a.redirectAuthError(w, errorMissingCode)
		return
	}
	var options []oauth2.AuthCodeOption
	if transaction.Mode == pkceS256 {
		options = append(options, oauth2.VerifierOption(transaction.Verifier))
	}
	config.RedirectURL = transaction.RedirectURI
	ctx := oidc.ClientContext(r.Context(), a.clientFunc())
	token, err := config.Exchange(ctx, query.Get("code"), options...)
	if err != nil {
		klog.Error("OIDC code exchange failed")
		a.redirectAuthError(w, errorInvalidCode)
		return
	}
	loginState, err := a.login(w, r, token)
	if err != nil {
		klog.Error("OIDC session construction failed")
		a.redirectAuthError(w, errorInternal)
		return
	}
	if a.metrics != nil {
		a.metrics.LoginSuccessful(a.k8sConfig, loginState)
	}
	klog.Info("OIDC login successful")
	complete(loginState.ToLoginJSON(), a.successURL, w)
}

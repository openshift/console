import type { FC } from 'react';
import { useState, useCallback, useEffect, useMemo } from 'react';
import {
  FormGroup,
  TextInput,
  FormHelperText,
  HelperText,
  HelperTextItem,
  Button,
  Radio,
  Form,
  ActionGroup,
  Alert,
  PageSection,
} from '@patternfly/react-core';
import { RhUiEditIcon } from '@patternfly/react-icons';
import * as _ from 'lodash';
import { useTranslation } from 'react-i18next';
import { useNavigate } from 'react-router';
import { k8sCreateResource } from '@console/dynamic-plugin-sdk/src/utils/k8s';
import { NsDropdown, resourcePathFromModel } from '@console/internal/components/utils';
import { useK8sWatchResource } from '@console/internal/components/utils/k8s-watch-hook';
import {
  ClusterExtensionModel,
  NamespaceModel,
  ServiceAccountModel,
} from '@console/internal/models';
import type { K8sResourceKind } from '@console/internal/module/k8s';
import SwitchToYAMLAlert from '@console/shared/src/components/alerts/SwitchToYAMLAlert';
import { SchemaFieldHelp } from '@console/shared/src/components/utils/SchemaFieldHelp';
import { useTextInputModal } from '@console/shared/src/hooks/useTextInputModal';
import { catalogNames, selectorForCatalogs } from './cluster-extension-catalog-selector';
import { ClusterExtensionCatalogsField } from './ClusterExtensionCatalogsField';
import { ClusterExtensionChannelsField } from './ClusterExtensionChannelsField';
import { ClusterExtensionVersionField } from './ClusterExtensionVersionField';
import { ServiceAccountDropdown } from './ServiceAccountDropdown';

interface ClusterExtensionFormProps {
  formData?: K8sResourceKind;
  onChange?: (data: K8sResourceKind) => void;
}

const ClusterExtensionForm: FC<ClusterExtensionFormProps> = ({ formData = {}, onChange }) => {
  const { t } = useTranslation('olm-v1');
  const navigate = useNavigate();
  const textInputModal = useTextInputModal();

  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Extract values from formData first
  const name = formData?.metadata?.name || '';
  const packageName = formData?.spec?.source?.catalog?.packageName || '';
  const namespace = formData?.spec?.namespace || '';
  const serviceAccountName = formData?.spec?.serviceAccount?.name || '';
  const version = formData?.spec?.source?.catalog?.version || '';
  const channels = useMemo(
    () => formData?.spec?.source?.catalog?.channels || [],
    [formData?.spec?.source?.catalog?.channels],
  );

  const catalogSelector = formData?.spec?.source?.catalog?.selector;
  const catalogs = useMemo(() => catalogNames(catalogSelector), [catalogSelector]);

  // Start with the auto-create radio button checked. Let useEffect hooks handle the rest.
  const [autoCreateNamespace, setAutoCreateNamespace] = useState(true);
  const [autoCreateServiceAccount, setAutoCreateServiceAccount] = useState(true);

  // Track auto-generated values separately from formData so that we can retain the values when
  // formData changes.
  const [autoGeneratedNamespace, setAutoGeneratedNamespace] = useState(
    name || 'operator-namespace',
  );
  const [autoGeneratedServiceAccountName, setAutoGeneratedServiceAccountName] = useState(
    name ? `${name}-service-account` : 'operator-service-account',
  );

  // Debounced name value for updating the auto-generated values when the name changes
  const [debouncedName, setDebouncedName] = useState(name);

  useEffect(() => {
    const timeoutId = setTimeout(() => {
      setDebouncedName(name);
    }, 500);

    return () => clearTimeout(timeoutId);
  }, [name]);

  // Helper to update formData at a specific path
  const updateFormDataPath = useCallback(
    (path: string | string[], value: any) => {
      if (!onChange) return;

      const updated = _.cloneDeep(formData);
      _.set(updated, path, value);
      onChange(updated);
    },
    [formData, onChange],
  );

  // Check if namespace exists
  const [namespaceResource, namespaceLoaded] = useK8sWatchResource<K8sResourceKind>(
    namespace
      ? {
          kind: NamespaceModel.kind,
          name: namespace,
        }
      : null,
  );

  // Check if service account exists in the selected namespace
  const [serviceAccountResource, serviceAccountLoaded] = useK8sWatchResource<K8sResourceKind>(
    namespace && serviceAccountName
      ? {
          kind: ServiceAccountModel.kind,
          name: serviceAccountName,
          namespace,
        }
      : null,
  );

  const namespaceExists = namespaceLoaded && !!namespaceResource;
  const serviceAccountExists = serviceAccountLoaded && !!serviceAccountResource;

  // Auto-switch to "Select from cluster" if the namespace exists
  useEffect(() => {
    if (namespaceExists && autoCreateNamespace) {
      setAutoCreateNamespace(false);
    }
  }, [namespaceExists, autoCreateNamespace]);

  // Auto-switch to "Select from cluster" if the service account exists
  useEffect(() => {
    if (serviceAccountExists && autoCreateServiceAccount) {
      setAutoCreateServiceAccount(false);
    }
  }, [serviceAccountExists, autoCreateServiceAccount]);

  // Auto-switch to "Create new ServiceAccount" if the namespace does not exist
  useEffect(() => {
    if (!namespaceExists) {
      setAutoCreateServiceAccount(true);
    }
  }, [namespaceExists]);

  // Update auto-generated values when debounced name changes
  useEffect(() => {
    setAutoGeneratedNamespace(debouncedName || 'operator-namespace');
    setAutoGeneratedServiceAccountName(
      debouncedName ? `${debouncedName}-service-account` : 'operator-service-account',
    );
  }, [debouncedName]);

  const handleNameChange = useCallback(
    (_event: any, value: string) => {
      updateFormDataPath('metadata.name', value);
    },
    [updateFormDataPath],
  );

  const handlePackageNameChange = useCallback(
    (_event: any, value: string) => {
      updateFormDataPath('spec.source.catalog.packageName', value);
    },
    [updateFormDataPath],
  );

  const handleNamespaceChange = useCallback(
    (value: string) => {
      updateFormDataPath('spec.namespace', value);
    },
    [updateFormDataPath],
  );

  const handleServiceAccountNameChange = useCallback(
    (value: string) => {
      updateFormDataPath('spec.serviceAccount.name', value);
    },
    [updateFormDataPath],
  );

  const handleVersionChange = useCallback(
    (value: string) => {
      updateFormDataPath('spec.source.catalog.version', value || undefined);
    },
    [updateFormDataPath],
  );

  const handleChannelsChange = useCallback(
    (values: string[]) => {
      updateFormDataPath('spec.source.catalog.channels', values.length ? values : undefined);
    },
    [updateFormDataPath],
  );

  const handleCatalogsChange = useCallback(
    (values: string[]) => {
      updateFormDataPath(
        'spec.source.catalog.selector',
        selectorForCatalogs(values, catalogSelector),
      );
    },
    [catalogSelector, updateFormDataPath],
  );

  const handleSubmit = useCallback(
    async (event: React.FormEvent<HTMLFormElement>) => {
      event.preventDefault();
      setIsSubmitting(true);
      setError(null);

      try {
        // Create namespace if "Create new Namespace" is selected
        if (autoCreateNamespace) {
          try {
            await k8sCreateResource({
              model: NamespaceModel,
              data: {
                metadata: {
                  name: namespace,
                },
              },
            });
          } catch (err) {
            // Ignore error if namespace already exists
            if (!err.message?.includes('already exists')) {
              throw err;
            }
          }
        }

        // Create service account if "Create new ServiceAccount" is selected
        if (autoCreateServiceAccount) {
          try {
            await k8sCreateResource({
              model: ServiceAccountModel,
              data: {
                metadata: {
                  name: serviceAccountName,
                  namespace,
                },
              },
            });
          } catch (err) {
            // Ignore error if service account already exists
            if (!err.message?.includes('already exists')) {
              throw err;
            }
          }
        }

        // Create the ClusterExtension
        const created = await k8sCreateResource({
          model: ClusterExtensionModel,
          data: formData,
        });
        navigate(resourcePathFromModel(ClusterExtensionModel, created.metadata.name));
      } catch (err) {
        setError(
          t('An error occurred creating the ClusterExtension: {{error}}', {
            error: err.toString(),
          }),
        );
      } finally {
        setIsSubmitting(false);
      }
    },
    [
      formData,
      navigate,
      t,
      autoCreateNamespace,
      autoCreateServiceAccount,
      namespace,
      serviceAccountName,
    ],
  );

  // Update formData when auto-generated namespace changes
  useEffect(() => {
    if (autoCreateNamespace) {
      updateFormDataPath('spec.namespace', autoGeneratedNamespace);
    }
  }, [autoCreateNamespace, autoGeneratedNamespace, updateFormDataPath]);

  // Update formData when auto-generated service account name changes
  useEffect(() => {
    if (autoCreateServiceAccount) {
      updateFormDataPath('spec.serviceAccount.name', autoGeneratedServiceAccountName);
    }
  }, [autoCreateServiceAccount, autoGeneratedServiceAccountName, updateFormDataPath]);

  return (
    <PageSection hasBodyWrapper={false}>
      <Form onSubmit={handleSubmit}>
        <SwitchToYAMLAlert />
        <FormGroup label={t('Name')} isRequired fieldId="cluster-extension-name">
          <TextInput
            isRequired
            type="text"
            id="cluster-extension-name"
            value={name}
            onChange={handleNameChange}
            aria-label={t('Name')}
          />
        </FormGroup>

        <FormGroup
          label={t('Package name')}
          isRequired
          fieldId="package-name"
          labelHelp={
            <SchemaFieldHelp
              model={ClusterExtensionModel}
              propertyPath="spec.source.catalog.packageName"
              headerContent={t('Package name')}
              ariaLabel={t('Package name help')}
              fallbackDescription={t('Name of the Operator package to install from a catalog.')}
            />
          }
        >
          <TextInput
            isRequired
            type="text"
            id="package-name"
            value={packageName}
            onChange={handlePackageNameChange}
            aria-label={t('Package name')}
          />
        </FormGroup>

        <FormGroup
          label={t('Namespace')}
          isRequired
          fieldId="namespace"
          labelHelp={
            <SchemaFieldHelp
              model={ClusterExtensionModel}
              propertyPath="spec.namespace"
              headerContent={t('Namespace')}
              ariaLabel={t('Namespace help')}
              fallbackDescription={t('Namespace where the Operator is installed.')}
            />
          }
        >
          <FormHelperText>
            <HelperText>
              <HelperTextItem>
                {t(
                  'Namespace for the Operator controller and manifests. A dedicated Operator namespace is recommended.',
                )}
              </HelperTextItem>
            </HelperText>
          </FormHelperText>
          <FormGroup role="radiogroup" fieldId="namespace-option" isStack>
            <Radio
              id="namespace-auto"
              name="namespace-option"
              label={
                <span
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    gap: '0.5rem',
                  }}
                >
                  <span>
                    {t('Automatically create a new Namespace: ')}
                    <strong>{autoGeneratedNamespace}</strong>
                  </span>
                  {autoCreateNamespace && (
                    <Button
                      variant="plain"
                      onClick={(e) => {
                        e.stopPropagation();
                        textInputModal({
                          title: t('Edit Namespace Name'),
                          label: t('Namespace'),
                          initialValue: autoGeneratedNamespace || name,
                          onSubmit: (value) => {
                            setAutoGeneratedNamespace(value);
                          },
                        });
                      }}
                      aria-label={t('Edit namespace name')}
                      style={{
                        padding: '0',
                        minWidth: 'auto',
                      }}
                    >
                      <RhUiEditIcon />
                    </Button>
                  )}
                </span>
              }
              onChange={() => {
                setAutoCreateNamespace(true);
                const newNamespace = name || 'operator-namespace';
                setAutoGeneratedNamespace(newNamespace);
                handleNamespaceChange(newNamespace);
              }}
              isChecked={autoCreateNamespace}
            />
            <Radio
              id="namespace-select"
              name="namespace-option"
              label={t('Select from cluster')}
              onChange={() => {
                setAutoCreateNamespace(false);
              }}
              isChecked={!autoCreateNamespace}
            />
            {!autoCreateNamespace && (
              <NsDropdown id="namespace" selectedKey={namespace} onChange={handleNamespaceChange} />
            )}
          </FormGroup>
        </FormGroup>

        <FormGroup
          label={t('Service Account')}
          isRequired
          fieldId="service-account"
          labelHelp={
            <SchemaFieldHelp
              model={ClusterExtensionModel}
              propertyPath="spec.serviceAccount.name"
              headerContent={t('Service Account')}
              ariaLabel={t('Service Account help')}
              fallbackDescription={t('Name of the service account in the installation namespace.')}
            />
          }
        >
          <FormHelperText>
            <HelperText>
              <HelperTextItem>
                {t(
                  'Service account must be in the selected namespace. A dedicated service account for the Operator is recommended.',
                )}
              </HelperTextItem>
            </HelperText>
          </FormHelperText>
          <FormGroup role="radiogroup" fieldId="service-account-option" isStack>
            <Radio
              id="service-account-auto"
              name="service-account-option"
              label={
                <span
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    gap: '0.5rem',
                  }}
                >
                  <span>
                    {t('Automatically create a new ServiceAccount: ')}
                    <strong>{autoGeneratedServiceAccountName}</strong>
                  </span>
                  {autoCreateServiceAccount && (
                    <Button
                      variant="plain"
                      onClick={(e) => {
                        e.stopPropagation();
                        textInputModal({
                          title: t('Edit ServiceAccount Name'),
                          label: t('Service Account Name'),
                          initialValue: autoGeneratedServiceAccountName,
                          onSubmit: (value) => {
                            setAutoGeneratedServiceAccountName(value);
                            handleServiceAccountNameChange(value);
                          },
                        });
                      }}
                      aria-label={t('Edit service account name')}
                      style={{
                        padding: '0',
                        minWidth: 'auto',
                      }}
                    >
                      <RhUiEditIcon />
                    </Button>
                  )}
                </span>
              }
              onChange={() => {
                setAutoCreateServiceAccount(true);
                const newServiceAccountName = name
                  ? `${name}-service-account`
                  : 'operator-service-account';
                setAutoGeneratedServiceAccountName(newServiceAccountName);
                handleServiceAccountNameChange(newServiceAccountName);
              }}
              isChecked={autoCreateServiceAccount}
            />
            <Radio
              id="service-account-select"
              name="service-account-option"
              label={t('Select from cluster')}
              isDisabled={!namespaceExists}
              onChange={() => {
                setAutoCreateServiceAccount(false);
              }}
              isChecked={!autoCreateServiceAccount}
            />
            {!autoCreateServiceAccount && namespaceExists && (
              <ServiceAccountDropdown
                id="service-account"
                namespace={namespace}
                selectedKey={serviceAccountName}
                onChange={handleServiceAccountNameChange}
              />
            )}
          </FormGroup>
        </FormGroup>

        <ClusterExtensionVersionField
          fieldId="version"
          value={version}
          onChange={handleVersionChange}
        />
        <ClusterExtensionChannelsField
          fieldId="channel"
          values={channels}
          onChange={handleChannelsChange}
        />
        <ClusterExtensionCatalogsField
          fieldId="catalogs"
          values={catalogs}
          onChange={handleCatalogsChange}
        />
        {error ? <Alert variant="danger" title={error} /> : null}
        <ActionGroup>
          <Button
            type="submit"
            variant="primary"
            isDisabled={isSubmitting}
            isLoading={isSubmitting}
          >
            {t('Create')}
          </Button>
          <Button type="button" variant="secondary" onClick={() => navigate(-1)}>
            {t('Cancel')}
          </Button>
        </ActionGroup>
      </Form>
    </PageSection>
  );
};

export default ClusterExtensionForm;
